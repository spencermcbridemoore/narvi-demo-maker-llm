#!/usr/bin/env bash
# Put the rubric grader (/grader + /grader/api/*) online behind a login.
#
# Run ON the instance from the repo root, with the stack already up:
#     bash deploy/enable-grader.sh [username]        # default username: teacher
#
# It hashes a password with the running Caddy (bcrypt), writes
# deploy/sites/grader.caddy (git-ignored; the Caddyfile imports deploy/sites/*.caddy)
# and reloads Caddy. DemoBuilder stays open; only /grader asks for the login.
# If Caddy rejects the route, or the script is interrupted before Caddy has checked
# it, the file is removed again (on a re-run, the previous one is put back), so a
# bad route is never left behind for the next restart.
# Re-run to change the password. To take the grader offline again:
#     rm deploy/sites/grader.caddy && docker compose -f deploy/docker-compose.yml restart caddy
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
COMPOSE=(docker compose -f deploy/docker-compose.yml)
USER_NAME="${1:-teacher}"
[[ "$USER_NAME" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "Username may use letters, digits, . _ - only." >&2; exit 1; }

read -r -s -p "New password for '${USER_NAME}' (10+ characters): " PW; echo
read -r -s -p "Repeat it: " PW2; echo
[ "$PW" = "$PW2" ] || { echo "Passwords differ." >&2; exit 1; }
[ "${#PW}" -ge 10 ] || { echo "Use at least 10 characters." >&2; exit 1; }

HASH="$("${COMPOSE[@]}" exec -T caddy caddy hash-password --plaintext "$PW" | tr -d '\r\n')"
[[ "$HASH" == \$2* ]] || { echo "Unexpected hash output from Caddy: $HASH" >&2; exit 1; }

SITE_FILE=deploy/sites/grader.caddy
mkdir -p deploy/sites
umask 077
# Never leave a route Caddy has not accepted: the Caddyfile imports it, so at the next
# restart Caddy would not start, and DemoBuilder would go down with the grader. Until
# Caddy has validated the new route, any exit (a rejection, Ctrl-C, a dropped SSH
# session) puts things back: the previous route on a re-run, no route otherwise.
PREVIOUS=""
WRITTEN=0
ACCEPTED=0
put_back() {
  if [ "$WRITTEN" = 1 ] && [ "$ACCEPTED" = 0 ]; then
    rm -f "$SITE_FILE"
    if [ -n "$PREVIOUS" ]; then
      cp "$PREVIOUS" "$SITE_FILE"
      chmod 644 "$SITE_FILE"
    fi
  fi
  [ -z "$PREVIOUS" ] || rm -f "$PREVIOUS"
}
trap put_back EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP
if [ -f "$SITE_FILE" ]; then
  PREVIOUS="$(mktemp)"
  cp "$SITE_FILE" "$PREVIOUS"
fi
WRITTEN=1
cat > "$SITE_FILE" <<EOF
# Generated by deploy/enable-grader.sh. Do not commit (git-ignored).
@grader path /grader /grader/*
handle @grader {
	basic_auth {
		${USER_NAME} ${HASH}
	}
	@graderapi path /grader/api/*
	handle @graderapi {
		reverse_proxy backend:8000 {
			flush_interval -1
		}
	}
	handle {
		encode zstd gzip
		root * /srv
		try_files {path} /index.html
		file_server
	}
}
EOF
chmod 644 "$SITE_FILE"   # Caddy (another user in the container) must read it

if ! "${COMPOSE[@]}" exec -T caddy caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile; then
  if [ -n "$PREVIOUS" ]; then
    echo "Caddy rejected the new grader route. The previous one was put back; nothing changed." >&2
  else
    echo "Caddy rejected the grader route. ${SITE_FILE} was removed; the grader stays offline." >&2
  fi
  exit 1   # put_back does the restoring
fi
ACCEPTED=1
"${COMPOSE[@]}" exec -T caddy caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile

# The address Caddy really serves: SITE_ADDRESS as the running container sees it.
# A hostname gets HTTPS; ":80" is the plain-HTTP local test; a full URL is used as is.
grader_url() {
  local addr="${1%%[ ,]*}"   # the first address, if several are listed
  case "$addr" in
    "") echo "https://<your SITE_ADDRESS>/grader" ;;
    http://* | https://*) echo "${addr%/}/grader" ;;
    :80) echo "http://localhost/grader" ;;
    :443) echo "https://localhost/grader" ;;
    :*) echo "http://localhost${addr}/grader" ;;
    *:80) echo "http://${addr%:80}/grader" ;;
    *:443) echo "https://${addr%:443}/grader" ;;
    *) echo "https://${addr}/grader" ;;
  esac
}
SITE_ADDRESS="$("${COMPOSE[@]}" exec -T caddy printenv SITE_ADDRESS 2>/dev/null | tr -d '\r\n' || true)"
echo "Grader is online at $(grader_url "$SITE_ADDRESS") (user: ${USER_NAME})."
